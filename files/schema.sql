-- ClinicFlow prototype: secure Supabase data model.
-- Run ONCE in Supabase SQL Editor. Never put service_role keys in the browser.
-- Create test user accounts in Supabase Authentication before using them.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'patient' check (role in ('patient','doctor','nurse','frontdesk','admin'))
);
alter table public.profiles enable row level security;

-- New signups get ONLY the patient role; changing roles requires SQL admin access.
create or replace function public.create_clinicflow_profile()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data->>'full_name'), ''), split_part(new.email,'@',1)), 'patient')
  on conflict (id) do nothing;
  return new;
end; $$;
drop trigger if exists on_clinicflow_auth_signup on auth.users;
create trigger on_clinicflow_auth_signup after insert on auth.users
for each row execute function public.create_clinicflow_profile();

-- Backfill profiles if you created auth accounts before running this script.
insert into public.profiles(id, full_name, role)
select id, coalesce(nullif(trim(raw_user_meta_data->>'full_name'), ''), split_part(email,'@',1)), 'patient'
from auth.users on conflict (id) do nothing;

create or replace function public.is_clinicflow_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles
     where id = (select auth.uid()) and role in ('doctor','nurse','frontdesk','admin'));
$$;
revoke all on function public.is_clinicflow_staff() from public;
grant execute on function public.is_clinicflow_staff() to authenticated;

drop policy if exists profile_read on public.profiles;
create policy profile_read on public.profiles for select to authenticated
using (id = (select auth.uid()) or public.is_clinicflow_staff());

create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  patient_id uuid not null references public.profiles(id),
  patient text not null,
  doctor text not null,
  date date not null,
  time text not null check (time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  reason text not null default 'Consultation',
  status text not null default 'Scheduled',
  confirmed boolean not null default false,
  queue_position integer,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- Make the account identity authoritative, not client-supplied name or creator ID.
create or replace function public.validate_clinicflow_appointment()
returns trigger language plpgsql security definer set search_path=public as $$
declare p_name text;
begin
  select full_name into p_name from public.profiles where id = new.patient_id;
  if p_name is null then raise exception 'Unknown patient'; end if;
  new.patient = p_name;
  if tg_op = 'INSERT' then new.created_by = auth.uid(); end if;
  return new;
end; $$;
drop trigger if exists clinicflow_validate_appointment on public.appointments;
create trigger clinicflow_validate_appointment before insert or update on public.appointments
for each row execute function public.validate_clinicflow_appointment();
alter table public.appointments enable row level security;
create unique index if not exists clinicflow_doctor_slot_unique
on public.appointments(doctor, date, time)
where status not in ('Cancelled','No show');
create index if not exists clinicflow_patient_idx on public.appointments(patient_id);

drop policy if exists appointment_read on public.appointments;
create policy appointment_read on public.appointments for select to authenticated
using (patient_id = (select auth.uid()) or public.is_clinicflow_staff());
drop policy if exists appointment_create on public.appointments;
create policy appointment_create on public.appointments for insert to authenticated
with check (patient_id = (select auth.uid()) or public.is_clinicflow_staff());
drop policy if exists appointment_staff_update on public.appointments;
create policy appointment_staff_update on public.appointments for update to authenticated
using (public.is_clinicflow_staff()) with check (public.is_clinicflow_staff());

-- Patients may ONLY confirm their own already-scheduled appointment.
create or replace function public.confirm_my_appointment(target_appointment_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.appointments set confirmed = true, updated_at = now()
  where id = target_appointment_id and patient_id = auth.uid() and status = 'Scheduled';
  if not found then raise exception 'Appointment unavailable or not yours'; end if;
end; $$;
revoke all on function public.confirm_my_appointment(bigint) from public;
grant execute on function public.confirm_my_appointment(bigint) to authenticated;

create or replace function public.touch_appointment_updated_at()
returns trigger language plpgsql set search_path=public as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists touch_clinicflow_appointment on public.appointments;
create trigger touch_clinicflow_appointment before update on public.appointments
for each row execute function public.touch_appointment_updated_at();

create table if not exists public.appointment_notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  appointment_id bigint references public.appointments(id) on delete cascade,
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);
alter table public.appointment_notifications enable row level security;
create index if not exists notification_recipient_idx on public.appointment_notifications(recipient_id,created_at desc);
drop policy if exists notification_read on public.appointment_notifications;
create policy notification_read on public.appointment_notifications for select to authenticated
using (recipient_id = (select auth.uid()));
drop policy if exists notification_mark_read on public.appointment_notifications;
create policy notification_mark_read on public.appointment_notifications for update to authenticated
using (recipient_id = (select auth.uid())) with check (recipient_id = (select auth.uid()));

-- Notification rows are generated on server, never by untrusted browsers.
create or replace function public.notify_clinicflow_patient()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if tg_op = 'INSERT' and new.created_by is distinct from new.patient_id then
    insert into public.appointment_notifications(recipient_id,appointment_id,message)
    values(new.patient_id,new.id,'A new appointment was booked for you with ' || new.doctor || ' on ' || new.date::text || ' at ' || new.time || '.');
  elsif tg_op = 'UPDATE' and (old.date,old.time,old.doctor,old.status) is distinct from (new.date,new.time,new.doctor,new.status) then
    insert into public.appointment_notifications(recipient_id,appointment_id,message)
    values(new.patient_id,new.id,'Your appointment with ' || new.doctor || ' was updated. Please check ClinicFlow.');
  end if;
  return new;
end; $$;
drop trigger if exists clinicflow_booking_notification on public.appointments;
create trigger clinicflow_booking_notification after insert or update on public.appointments
for each row execute function public.notify_clinicflow_patient();

revoke all on public.profiles, public.appointments, public.appointment_notifications from anon;
grant select on public.profiles to authenticated;
grant select, insert, update on public.appointments to authenticated;
grant select on public.appointment_notifications to authenticated;
grant update(read_at) on public.appointment_notifications to authenticated;

-- Use Realtime's published Postgres changes for live UI updates.
do $$ begin
  if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='appointments') then
    alter publication supabase_realtime add table public.appointments;
  end if;
  if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='appointment_notifications') then
    alter publication supabase_realtime add table public.appointment_notifications;
  end if;
end $$;

